# Cell 5: Convert molecules to graphs
import torch
from torch_geometric.data import Data

def atom_features(atom):
    """
    Each atom becomes a feature vector. These are standard choices
    from the MoleculeNet / DeepChem literature.
    """
    return [
        atom.GetAtomicNum(),              # which element
        atom.GetDegree(),                 # number of bonded neighbours
        atom.GetFormalCharge(),           # +1, 0, -1 etc.
        int(atom.GetHybridization()),     # sp, sp2, sp3 ...
        int(atom.GetIsAromatic()),        # part of an aromatic ring?
        atom.GetTotalNumHs(),             # attached hydrogens
        int(atom.IsInRing()),             # in any ring?
    ]

def mol_to_graph(mol, label):
    x = torch.tensor([atom_features(a) for a in mol.GetAtoms()], dtype=torch.float)

    # Edges: one bond becomes two directed edges, since the graph is undirected
    src, dst = [], []
    for bond in mol.GetBonds():
        i, j = bond.GetBeginAtomIdx(), bond.GetEndAtomIdx()
        src += [i, j]
        dst += [j, i]
    edge_index = torch.tensor([src, dst], dtype=torch.long)

    return Data(x=x, edge_index=edge_index,
                y=torch.tensor([label], dtype=torch.float))

graphs = [mol_to_graph(m, l) for m, l in zip(df["mol"], df["p_np"])]

# Drop any molecule with no bonds (single atoms break message passing)
valid = [i for i, g in enumerate(graphs) if g.edge_index.shape[1] > 0]
print(f"Graphs with at least one bond: {len(valid)} / {len(graphs)}")

