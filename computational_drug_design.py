# Cell 6: GCN model and training
import torch.nn as nn
import torch.nn.functional as F
from torch_geometric.nn import GCNConv, global_mean_pool
from torch_geometric.loader import DataLoader

class GCN(nn.Module):
    def __init__(self, in_dim=7, hidden=64, dropout=0.3):
        super().__init__()
        self.conv1 = GCNConv(in_dim, hidden)
        self.conv2 = GCNConv(hidden, hidden)
        self.conv3 = GCNConv(hidden, hidden)
        self.dropout = nn.Dropout(dropout)
        self.lin = nn.Linear(hidden, 1)

    def forward(self, data):
        x, edge_index, batch = data.x, data.edge_index, data.batch
        # 3 rounds of message passing: each atom gathers info from
        # neighbours up to 3 bonds away
        x = F.relu(self.conv1(x, edge_index))
        x = F.relu(self.conv2(x, edge_index))
        x = F.relu(self.conv3(x, edge_index))
        # Pool all atoms into one vector per molecule
        x = global_mean_pool(x, batch)
        x = self.dropout(x)
        return self.lin(x).squeeze(-1)


def run_gcn(seed, epochs=100, lr=1e-3, hidden=64):
    torch.manual_seed(seed)
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    train_set = [graphs[i] for i in train_idx]
    valid_set = [graphs[i] for i in valid_idx]
    test_set  = [graphs[i] for i in test_idx]

    train_loader = DataLoader(train_set, batch_size=64, shuffle=True)
    valid_loader = DataLoader(valid_set, batch_size=256)
    test_loader  = DataLoader(test_set,  batch_size=256)

    model = GCN(hidden=hidden).to(device)
    opt = torch.optim.Adam(model.parameters(), lr=lr)
    # Class imbalance: weight the positive class by its inverse frequency
    pos_weight = torch.tensor([(1 - y[train_idx].mean()) / y[train_idx].mean()]).to(device)
    criterion = nn.BCEWithLogitsLoss(pos_weight=pos_weight)

    @torch.no_grad()
    def evaluate(loader):
        model.eval()
        probs, labels = [], []
        for batch in loader:
            batch = batch.to(device)
            probs.append(torch.sigmoid(model(batch)).cpu())
            labels.append(batch.y.cpu())
        return roc_auc_score(torch.cat(labels), torch.cat(probs))

    best_valid, best_test = 0, 0
    for epoch in range(1, epochs + 1):
        model.train()
        for batch in train_loader:
            batch = batch.to(device)
            opt.zero_grad()
            loss = criterion(model(batch), batch.y)
            loss.backward()
            opt.step()

        # Early-stopping style selection: keep the test score from the
        # epoch where validation was best. Validation never trains the model.
        v = evaluate(valid_loader)
        if v > best_valid:
            best_valid, best_test = v, evaluate(test_loader)

        if epoch % 20 == 0:
            print(f"  epoch {epoch:3d} | valid {v:.4f} | best valid {best_valid:.4f}")

    return best_valid, best_test


