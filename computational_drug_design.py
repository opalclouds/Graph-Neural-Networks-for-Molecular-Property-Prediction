# Cell 3: Scaffold split
from rdkit.Chem.Scaffolds import MurckoScaffold
from collections import defaultdict
import numpy as np

def scaffold_split(df, frac_train=0.8, frac_valid=0.1, seed=0):

    scaffolds = defaultdict(list)
    for i, mol in enumerate(df["mol"]):
        core = MurckoScaffold.MurckoScaffoldSmiles(mol=mol, includeChirality=False)
        scaffolds[core].append(i)

    # Sort groups: biggest first (standard DeepChem behaviour)
    groups = sorted(scaffolds.values(), key=lambda x: (len(x), x[0]), reverse=True)

    n = len(df)
    n_train, n_valid = frac_train * n, frac_valid * n
    train, valid, test = [], [], []
    for g in groups:
        if len(train) + len(g) <= n_train:
            train += g
        elif len(valid) + len(g) <= n_valid:
            valid += g
        else:
            test += g
    return train, valid, test

train_idx, valid_idx, test_idx = scaffold_split(df)

