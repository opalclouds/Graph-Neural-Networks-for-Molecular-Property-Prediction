# Cell 8: Better features + GIN
from torch_geometric.nn import GINConv, global_add_pool

ATOMS = [6, 7, 8, 9, 15, 16, 17, 35, 53]  # C N O F P S Cl Br I

def atom_features_v2(atom):
    f = [0] * (len(ATOMS) + 1)
    num = atom.GetAtomicNum()
    f[ATOMS.index(num) if num in ATOMS else len(ATOMS)] = 1   # one-hot element

    deg = [0] * 6
    deg[min(atom.GetDegree(), 5)] = 1

    hyb = [0] * 5
    hyb[min(int(atom.GetHybridization()), 4)] = 1

    hs = [0] * 5
    hs[min(atom.GetTotalNumHs(), 4)] = 1

    return f + deg + hyb + hs + [
        atom.GetFormalCharge(),
        int(atom.GetIsAromatic()),
        int(atom.IsInRing()),
    ]

def mol_to_graph_v2(mol, label):
    x = torch.tensor([atom_features_v2(a) for a in mol.GetAtoms()], dtype=torch.float)
    src, dst = [], []
    for b in mol.GetBonds():
        i, j = b.GetBeginAtomIdx(), b.GetEndAtomIdx()
        src += [i, j]; dst += [j, i]
    return Data(x=x, edge_index=torch.tensor([src, dst], dtype=torch.long),
                y=torch.tensor([label], dtype=torch.float))

graphs_v2 = [mol_to_graph_v2(m, l) for m, l in zip(df["mol"], df["p_np"])]
IN_DIM = graphs_v2[0].x.shape[1]
print("Feature dim:", IN_DIM)


class GIN(nn.Module):
    """GIN is provably more expressive than GCN at distinguishing graph structures."""
    def __init__(self, in_dim, hidden=64, dropout=0.5):
        super().__init__()
        def mlp(i, o):
            return nn.Sequential(nn.Linear(i, o), nn.ReLU(), nn.Linear(o, o))
        self.conv1 = GINConv(mlp(in_dim, hidden))
        self.conv2 = GINConv(mlp(hidden, hidden))
        self.bn1 = nn.BatchNorm1d(hidden)
        self.bn2 = nn.BatchNorm1d(hidden)
        self.dropout = nn.Dropout(dropout)
        self.lin = nn.Linear(hidden, 1)

    def forward(self, data):
        x, ei, batch = data.x, data.edge_index, data.batch
        x = F.relu(self.bn1(self.conv1(x, ei)))
        x = F.relu(self.bn2(self.conv2(x, ei)))
        x = global_add_pool(x, batch)
        return self.lin(self.dropout(x)).squeeze(-1)


def run_gin(seed, epochs=60, lr=1e-3):
    torch.manual_seed(seed)
    device = torch.device("cuda")
    tr = DataLoader([graphs_v2[i] for i in train_idx], batch_size=64, shuffle=True)
    va = DataLoader([graphs_v2[i] for i in valid_idx], batch_size=256)
    te = DataLoader([graphs_v2[i] for i in test_idx],  batch_size=256)

    model = GIN(IN_DIM).to(device)
    opt = torch.optim.Adam(model.parameters(), lr=lr, weight_decay=1e-4)
    pw = torch.tensor([(1 - y[train_idx].mean()) / y[train_idx].mean()]).to(device)
    crit = nn.BCEWithLogitsLoss(pos_weight=pw)

    @torch.no_grad()
    def ev(loader):
        model.eval()
        p, l = [], []
        for b in loader:
            b = b.to(device)
            p.append(torch.sigmoid(model(b)).cpu()); l.append(b.y.cpu())
        return roc_auc_score(torch.cat(l), torch.cat(p))

    best_v, best_t = 0, 0
    for _ in range(epochs):
        model.train()
        for b in tr:
            b = b.to(device)
            opt.zero_grad(); crit(model(b), b.y).backward(); opt.step()
        v = ev(va)
        if v > best_v:
            best_v, best_t = v, ev(te)
    return best_v, best_t


